# frozen_string_literal: true

require "fileutils"
require "open3"
require "prism"
require "rbconfig"

module RbsInfer
  module Extensions
    module ConcurrentRuby
      # Puts the concurrent-ruby source that `Concurrent::Map` runs on this engine
      # where the checker can read it: every file of the gem that
      # `require "concurrent/map"` loads, verbatim, at its path under the gem's lib.
      #
      # Which files those are is measured in a fresh interpreter rather than
      # listed, because `map.rb` picks its backend by `RUBY_ENGINE` and requires
      # only that one.
      #
      # Every `def` is marked `# @rbs_infer |...`: gem_rbs_collection already
      # declares `Concurrent::Map`'s methods, and a second plain declaration of one
      # takes down the whole environment. The core keeps the mark only where
      # another signature declares the method.
      class RuntimeGenerator
        SIDECAR_DIR = "sig/generated/steep_concurrent_runtime"
        ENTRY = "concurrent/map"

        OVERLOAD_MARKER = "# @rbs_infer |..."

        HEADER = <<~HEADER
          # GENERATED by RbsInfer::Extensions::ConcurrentRuby::RuntimeGenerator.
          # Regenerated on every run; do not edit.
          #
          # Transcribed from the installed concurrent-ruby.

        HEADER

        def initialize(app_dir:)
          @app_dir = app_dir
        end

        # => [{ filename:, source: }] — empty when concurrent-ruby is not installed.
        def build
          lib = gem_lib or return []

          loaded_files.select { |file| file.start_with?(lib) }.map do |file|
            { filename: file.delete_prefix(lib), source: HEADER + marked(File.read(file)) }
          end
        end

        def generate
          files = build
          dir = File.join(@app_dir, SIDECAR_DIR)

          FileUtils.rm_rf(dir)
          files.each do |file|
            path = File.join(dir, file[:filename])
            FileUtils.mkdir_p(File.dirname(path))
            File.write(path, file[:source])
          end

          dir
        end

        private

        def marked(source)
          def_lines = RbsInfer::Analyzer.find_all_nodes(Prism.parse(source).value) { |node| node.is_a?(Prism::DefNode) }
                                        .to_set { |node| node.location.start_line }
          source.lines.each_with_index.map do |line, index|
            def_lines.include?(index + 1) ? "#{line[/\A */]}#{OVERLOAD_MARKER}\n#{line}" : line
          end.join
        end

        def gem_lib
          spec = Gem.loaded_specs["concurrent-ruby"] || Gem::Specification.find_by_name("concurrent-ruby")
          File.join(spec.full_gem_path, "lib", "concurrent-ruby", "")
        rescue Gem::MissingSpecError
          nil
        end

        def loaded_files
          script = "before = $LOADED_FEATURES.dup; require #{ENTRY.inspect}; puts $LOADED_FEATURES - before"
          output, status = Open3.capture2(RbConfig.ruby, "-e", script, chdir: @app_dir)
          status.success? ? output.lines(chomp: true) : []
        end
      end
    end
  end
end
