# frozen_string_literal: true

require_relative "../../../framework_source"

module RbsInfer
  module Extensions
    module Rails
      module ActiveSupport
        module Runtime
          # Slices `class_attribute` out of the installed ActiveSupport:
          # `Class#class_attribute` and the `ActiveSupport::ClassAttribute` store
          # it hands each attribute to.
          #
          # The macro writes its readers and writers with `class_eval` on a string
          # it builds, and its storage with `define_method` blocks
          # (`ClassAttribute.redefine`). Both are read by the checker at each call
          # site, and `Project::StringEvalMacroExpander` places what the string
          # folds to, so a reader such as `pluralize_table_names` has a body
          # instead of only gem_rbs_collection's declaration
          # (felixefelip/rbs_infer#540).
          module ClassAttributeTranscriber
            MACRO = :class_attribute
            STORE = "ActiveSupport::ClassAttribute"
            STORE_METHOD = :redefine

            FILENAME = "class_attribute.rb"

            # gem_rbs_collection declares `class_attribute` with `untyped`
            # parameters, which would stop the call site's literals from reaching
            # the body; the store it does not declare, so the store is not marked.
            OVERLOAD_MARKER = "# @rbs_infer |..."

            module_function

            # => { filename:, source: }, or nil when the macro or the store
            # cannot be sliced from the installed gem.
            def file_entry
              macro = macro_source or return nil
              store = store_source or return nil

              { filename: FILENAME, source: "#{header}#{store}\n#{macro}" }
            end

            def macro_source
              load_active_support or return nil

              node = FrameworkSource.def_node(::Class.instance_method(MACRO)) or return nil
              body = "#{OVERLOAD_MARKER}\n#{FrameworkSource.source(node)}".rstrip
              "class Class\n#{FrameworkSource.indent(body, 1)}\nend\n"
            rescue NameError
              nil
            end

            # The whole `module ClassAttribute`, nested back into
            # `module ActiveSupport`: `redefine` calls its sibling `redefine_method`.
            def store_source
              load_active_support or return nil

              file, line = Object.const_get(STORE).method(STORE_METHOD).source_location
              return nil unless file && line && File.file?(file)

              namespace, name = STORE.split("::")
              node = FrameworkSource.enclosing_namespace(file, line, name) or return nil

              "module #{namespace}\n#{FrameworkSource.indent(FrameworkSource.source(node).rstrip, 1)}\nend\n"
            rescue NameError
              nil
            end

            def load_active_support
              require "active_support"
              require "active_support/core_ext/class/attribute"
              true
            rescue LoadError
              false
            end

            def header
              <<~HEADER
                # frozen_string_literal: true
                #
                # GENERATED by RbsInfer::Extensions::Rails::ActiveSupport::RuntimeGenerator.
                # Regenerated on every run; do not edit.
                #
                # `class_attribute`, transcribed from the installed ActiveSupport. The
                # methods it defines are written with `class_eval` on a STRING and with
                # `define_method` blocks, so the source is put here, and
                # `Project::StringEvalMacroExpander` renders the string at the call
                # sites that supply the folding. Nothing in this file, or in the
                # generator that wrote it, states a type.

              HEADER
            end
          end
        end
      end
    end
  end
end
