# frozen_string_literal: true

require_relative "../../../framework_source"

module RbsInfer
  module Extensions
    module Rails
      module ActiveSupport
        module Runtime
          # The part of the installed i18n gem the inflector runs: a locale's
          # rules are found through `I18n.fallbacks[locale]`
          # (`Inflections.instance_or_fallback`), and those fallbacks are an
          # `I18n::Locale::Fallbacks` computing each chain from
          # `I18n::Locale::Tag`.
          #
          # Which files that is, is measured: the `i18n/locale` files a lookup
          # like the inflector's (`I18n.fallbacks[:en]`) loads, through the
          # gem's `autoload`s, in whole, minus their `require`s. Of
          # `i18n/backend/fallbacks.rb`, only what it defines on `I18n` itself
          # (`@@fallbacks` and its reader and writer); its `Backend::Fallbacks`
          # is the translation backend, which nothing here reaches.
          module I18nTranscriber
            FILENAME = "i18n.rb"
            LOCALE_FILES = %r{/lib/i18n/locale(/.*)?\.rb\z}

            # gem_rbs_collection declares i18n, so each `def` is marked.
            OVERLOAD_MARKER = "# @rbs_infer |..."

            module_function

            # => { filename:, source: }, or nil when the gem or a piece of it
            # cannot be read.
            def file_entry
              locale_files = loaded_locale_files or return nil
              fallbacks = fallbacks_source or return nil

              pieces = [fallbacks, *locale_files.map { |file| gem_file(file) }]
              body = pieces.map { |piece| FrameworkSource.mark_defs(piece, OVERLOAD_MARKER) }.join("\n")
              { filename: FILENAME, source: header + body }
            end

            def loaded_locale_files
              gem_dir = i18n_gem_dir or return nil
              files = $LOADED_FEATURES.select do |file|
                file.start_with?(gem_dir) && file.match?(LOCALE_FILES) && File.file?(file)
              end
              files.empty? ? nil : files.uniq.sort
            end

            # Loads the inflector and runs the lookup it makes, so the gem's
            # `autoload`s load what that lookup reaches.
            def i18n_gem_dir
              require "active_support"
              require "active_support/core_ext/string/inflections"
              ::I18n.fallbacks[:en]
              Gem.loaded_specs["i18n"]&.full_gem_path
            rescue LoadError, NameError
              nil
            end

            # `module I18n` as `i18n/backend/fallbacks.rb` writes it, without its
            # `Backend` module.
            def fallbacks_source
              namespace = fallbacks_namespace or return nil
              kept = namespace.body.body.reject { |node| node.is_a?(Prism::ModuleNode) && node.name == :Backend }
              body = kept.map { |node| "#{FrameworkSource.source(node).rstrip}\n" }.join("\n")
              "module I18n\n#{FrameworkSource.indent(body, 1)}end\n"
            end

            def fallbacks_namespace
              file, line = ::I18n.method(:fallbacks).source_location
              FrameworkSource.enclosing_namespace(file, line, "I18n") if file && File.file?(file)
            rescue NameError
              nil
            end

            def gem_file(file)
              FrameworkSource.without_requires(File.read(file)).sub(/\A# frozen_string_literal: true\n\n?/, "")
            end

            def header
              <<~HEADER
                # frozen_string_literal: true
                #
                # GENERATED by RbsInfer::Extensions::Rails::ActiveSupport::RuntimeGenerator.
                # Regenerated on every run; do not edit.
                #
                # `I18n.fallbacks` and the `I18n::Locale` files the inflector loads,
                # transcribed from the installed i18n gem. Nothing in this file, or
                # in the generator that wrote it, states a type.

              HEADER
            end
          end
        end
      end
    end
  end
end
