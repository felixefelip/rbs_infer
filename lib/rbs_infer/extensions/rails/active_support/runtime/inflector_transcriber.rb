# frozen_string_literal: true

require_relative "../../../framework_source"

module RbsInfer
  module Extensions
    module Rails
      module ActiveSupport
        module Runtime
          # Slices `String#singularize` out of the installed ActiveSupport, with
          # what it runs: `Inflector.singularize` and `pluralize`, the
          # `apply_inflections` they share, the `Inflections` store they read,
          # and the English rules ActiveSupport fills that store with at load
          # time.
          #
          # A macro that names a method after its argument
          # (`"#{name.to_s.singularize}_ids"`) folds only when the checker can
          # follow `singularize` to a literal (felixefelip/rbs_infer#569). The
          # rules are the gem's, so the answer is the gem's; nothing here knows
          # that "comments" singularizes to "comment".
          #
          # The store file and the rules file go in whole, minus their
          # `require`s. Of `inflector/methods.rb`, only the methods the entry
          # reaches: the rest of the file reads regexes and acronym tables
          # nothing calls yet.
          module InflectorTranscriber
            INFLECTOR = "ActiveSupport::Inflector"
            INFLECTOR_METHODS = %i[singularize pluralize apply_inflections].freeze
            STRING_METHODS = %i[singularize].freeze
            RULES_FEATURE = "active_support/inflections"

            FILENAME = "inflector.rb"

            # gem_rbs_collection declares every one of these methods, the store's
            # included, so each `def` is marked.
            OVERLOAD_MARKER = "# @rbs_infer |..."

            module_function

            # => { filename:, source: }, or nil when a piece cannot be sliced
            # from the installed gem.
            def file_entry
              load_active_support or return nil

              pieces = [store_source, inflector_source, string_source, rules_source]
              return nil if pieces.any?(&:nil?)

              body = pieces.map { |piece| FrameworkSource.mark_defs(piece, OVERLOAD_MARKER) }.join("\n")
              { filename: FILENAME, source: header + body }
            rescue NameError
              nil
            end

            # `inflector/inflections.rb`: the `Inflections` store and the
            # `Inflector.inflections` that memoizes one per locale.
            def store_source
              file, = inflector.instance_method(:inflections).source_location
              file && File.file?(file) ? gem_file(file) : nil
            end

            # Reopens `Inflector` with the methods the entry reaches, each under
            # the visibility the gem gives it.
            def inflector_source
              public_names, private_names = INFLECTOR_METHODS.partition { inflector.public_method_defined?(_1) }
              public_body = method_sources(inflector, public_names) or return nil
              private_body = method_sources(inflector, private_names) or return nil

              body = private_names.empty? ? public_body : "#{public_body}\nprivate\n\n#{private_body}"
              "module ActiveSupport\n  module Inflector\n#{FrameworkSource.indent(body, 2)}  end\nend\n"
            end

            def string_source
              body = method_sources(::String, STRING_METHODS) or return nil
              "class String\n#{FrameworkSource.indent(body, 1)}end\n"
            end

            # The file `require "active_support/inflections"` loads, found the way
            # `require` finds it.
            def rules_source
              _, file = $LOAD_PATH.resolve_feature_path(RULES_FEATURE)
              file && File.file?(file) ? gem_file(file) : nil
            end

            def method_sources(owner, names)
              names.map do |name|
                node = FrameworkSource.def_node(owner.instance_method(name)) or return nil
                "#{FrameworkSource.source(node).rstrip}\n"
              end.join("\n")
            end

            def gem_file(file)
              FrameworkSource.without_requires(File.read(file)).sub(/\A# frozen_string_literal: true\n\n?/, "")
            end

            # Reached by name: `ActiveSupport` inside this namespace is OUR module.
            def inflector
              Object.const_get(INFLECTOR)
            end

            def load_active_support
              require "active_support"
              require "active_support/core_ext/string/inflections"
              true
            rescue LoadError
              false
            end

            def header
              <<~HEADER
                # frozen_string_literal: true
                #
                # GENERATED by RbsInfer::Extensions::Rails::ActiveSupport::RuntimeGenerator.
                # Regenerated on every run; do not edit.
                #
                # `String#singularize`, transcribed from the installed ActiveSupport
                # with the inflector methods it runs, the `Inflections` store they
                # read and the English rules the gem loads into it. Nothing in this
                # file, or in the generator that wrote it, states a type.

              HEADER
            end
          end
        end
      end
    end
  end
end
