# frozen_string_literal: true

require "fileutils"
require "pathname"
require_relative "string_eval_sidecar"
require_relative "string_eval_macro_expander"

module RbsInfer::Project
  # Writes what each `class_eval`-a-string call site defines as Ruby the
  # checker reads, one file per file that makes such calls:
  #
  #   sig/generated/steep_string_evals/app/models/post.rb
  #
  #   class Post
  #     def user_email(...)
  #       _ = user
  #       _.email(...)
  #     rescue NoMethodError => e
  #       …
  #     end
  #   end
  #
  # The methods exist at run time, so their bodies are part of the program. They
  # used to be appended to the target's source in this process alone, which
  # gave them RBS and nothing else: `steep check` never saw them, so a body was
  # never checked, inferred no precondition (`not_nil self.user` for the
  # `delegate` above) and narrowed nothing. As a checked file they are read
  # like any other code, by Steep and by this pipeline alike, and this file is
  # the one place the methods are written down.
  #
  # Nothing here reads a macro. `StringEvalMacroExpander` decides where each
  # folded chunk lands, from the sidecar `steep check` wrote; this only puts
  # its answer where the checker reads Ruby. The directory is not dot-prefixed:
  # it is reached through a Steepfile's `check "sig/**/*.rb"`, and `**` skips
  # hidden directories.
  module StringEvalSources
    SIDECAR_DIR = "sig/generated/steep_string_evals"

    HEADER = <<~HEADER
      # frozen_string_literal: true
      #
      # GENERATED by rbs_infer from sig/generated/.steep_string_evals.yml.
      # Regenerated on every run; do not edit.
      #
      # What each `class_eval` of a string in %<path>s defines at run time,
      # placed in the class that made the call, so the checker reads the bodies.
    HEADER

    module_function

    # Rewrites the directory under `base_dir` from `sidecar`, dropping the
    # files of call sites that are gone. Returns the paths written.
    def generate(base_dir:, sidecar:)
      base = Pathname(base_dir).expand_path
      dir = base + SIDECAR_DIR
      FileUtils.rm_rf(dir)

      render(base_dir: base, sidecar: sidecar).map do |path, content|
        output = dir + path
        FileUtils.mkdir_p(output.dirname)
        output.write(content)
        output.to_s
      end
    end

    # `{ source path => file content }`, relative to the project, for every
    # file that makes a call the sidecar recorded and the project still has.
    def render(base_dir:, sidecar:)
      base = Pathname(base_dir).expand_path

      sidecar.paths.each_with_object({}) do |path, files|
        # A file this writes holds no macro call of its own; one that did would
        # be read back as its own source.
        next if path.start_with?("#{SIDECAR_DIR}/")

        source_path = base + path
        next unless source_path.file?

        reopens = StringEvalMacroExpander.reopens(source_path.read, path: source_path.to_s, sidecar: sidecar)
        files[path] = "#{format(HEADER, path: path)}\n#{reopens}" if reopens
      end
    end
  end
end
