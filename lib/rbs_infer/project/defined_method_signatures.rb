# frozen_string_literal: true

require "pathname"
require "yaml"

module RbsInfer
  module Project
    # Declares the methods `steep check` found a specialized body defining with
    # `define_method` (felixefelip/steep#431):
    #
    #   def self.redefine_method(owner, name, &block)
    #     owner.define_method(name, &block)   # Base.__class_attr_pluralize
    #   end
    #
    # The method exists at run time, and its body is the block, which the
    # checker reads where it is written. What it lacks is a signature: a call to
    # a method no signature names does not resolve, so nothing would ever be
    # specialized against it. The checker writes what it found to
    # `sig/generated/.steep_defined_methods.yml`, with the block's parameters and
    # what every call returns, or `untyped` before any call does; this writes
    # that down as RBS, one reopening per class.
    #
    # A method another signature already declares is left to it.
    module DefinedMethodSignatures
      SIDECAR = "sig/generated/.steep_defined_methods.yml"
      OUTPUT = "sig/generated/steep_defined_methods.rbs"
      SCHEMA_VERSION = 1

      HEADER = <<~HEADER.freeze
        # GENERATED by rbs_infer from #{SIDECAR}.
        # Regenerated on every run; do not edit.
        #
        # Methods a body defines with `define_method`, declared so their calls resolve.
      HEADER

      module_function

      # Writes `OUTPUT` under `base_dir`, or removes it when nothing is left to
      # declare. Returns its path when that changed it, nil otherwise.
      def generate(base_dir:, resolver:)
        base = Pathname(base_dir).expand_path
        path = base + OUTPUT
        before = path.file? ? path.read : nil
        content = render(load(base + SIDECAR), resolver: resolver)
        return nil if content == before

        content ? path.dirname.mkpath && path.write(content) : path.delete
        path
      end

      # The RBS for `methods` (`key => { "params", "returns" }`), or nil when
      # none is left to declare.
      def render(methods, resolver:)
        return nil if methods.empty?

        env = RbsInfer::Signatures::SteepEnvironment.definition_builder&.env
        reopens = declarations(methods, resolver).sort.filter_map { |owner, defs| reopening(owner, defs.sort, env) }
        "#{HEADER}\n#{reopens.join("\n")}" unless reopens.empty?
      end

      # `owner => [def line, …]` for the methods no other signature declares.
      # This file's own previous output does not count.
      def declarations(methods, resolver)
        methods.each_with_object({}) do |(key, signature), owners|
          owner, separator, name = key.rpartition(/[.#]/)
          singleton = separator == "."
          next if resolver.foreign_own_declaration?(owner, name, singleton: singleton,
                                                                 excluding_suffix: "/#{File.basename(OUTPUT)}")

          (owners[owner] ||= []) << declaration(name, singleton, signature)
        end
      end

      def declaration(name, singleton, signature)
        "def #{"self." if singleton}#{name}: #{signature["params"]} -> #{signature["returns"]}"
      end

      def reopening(owner, defs, env)
        entry = env&.class_decls&.[](RBS::TypeName.parse("::#{owner}")) or return nil
        keyword = entry.is_a?(RBS::Environment::ModuleEntry) ? "module" : "class"
        params = entry.primary_decl.type_params
        header = params.empty? ? "#{keyword} #{owner}" : "#{keyword} #{owner}[#{params.join(", ")}]"

        "#{header}\n#{defs.map { |line| "  #{line}" }.join("\n")}\nend\n"
      end

      def load(path)
        methods = written_methods(path) or return {}

        methods.select { |key, signature| key.is_a?(String) && signature.is_a?(Hash) }
      rescue StandardError => e
        warn "[rbs_infer] failed to load #{path}: #{e.class}: #{e.message}"
        {}
      end

      def written_methods(path)
        raw = path.file? ? YAML.safe_load(path.read) : nil
        methods = raw["methods"] if raw.is_a?(Hash) && raw["version"] == SCHEMA_VERSION
        methods if methods.is_a?(Hash)
      end
    end
  end
end
