# frozen_string_literal: true

require "fileutils"

module RbsInfer::Project
  # Emits pseudo-code for what the LANGUAGE runs on a declaration. `Module#include` is
  # written in C, so nothing in a project says that `include M` runs `M.included(self)`
  # — and that call is the only thing that says which class a hook's parameter is.
  #
  # So write `Module#include`, once — transcribed from `rb_mod_include` in MRI's
  # `eval.c`, which is:
  #
  #   rb_check_arity(argc, 1, UNLIMITED_ARGUMENTS);
  #   ...
  #   while (argc--) {
  #       rb_funcall(argv[argc], id_append_features, 1, module);
  #       rb_funcall(argv[argc], id_included, 1, module);
  #   }
  #   return module;
  #
  # Three things in there the pseudo-code has to say, or it is describing some other
  # method: `while (argc--)` walks the arguments BACKWARDS (which is why `include A, B`
  # leaves `A` closest in the ancestors); `append_features` is where the chain is
  # actually spliced (`rb_include_module`); and `rb_funcall` dispatches by name
  # IGNORING visibility — both of those methods are private on `Module`, and `included`
  # is a no-op there (`rb_obj_dummy1`), so the plain-call spelling `mod.included(self)`
  # asserts a public call Ruby never makes. `send` is what `rb_funcall` is.
  #
  # The two it delegates to are written here as well, under `private` because that is
  # their visibility on `Module` (measured: `Module.instance_method(:included).owner` is
  # `Module`, and RBS core declares both `private def`). Neither can state its whole
  # effect — the splice is `rb_include_module` and the hook is `rb_obj_dummy1` — but
  # writing them gives an app's override a `super` that resolves, which is what
  # `ActiveSupport::Concern#append_features` needs.
  #
  # `extend` is the same story told about the singleton: `rb_obj_extend` in object.c
  # runs `extend_object` and then `extended`, so `extend Deferring` is what says that
  # `Deferring.extended(Shared)` ran — and that call is the only thing that says which
  # module a hook's parameter is. Without it a pass can only ASSUME the hook fired,
  # which is what felixefelip/rbs_infer#302 is about.
  #
  # Nothing here states a type; the same rule the Devise and AR-runtime generators
  # follow. `# @rbs_infer |...` (#200) makes the emitted signature RBS's overloading
  # form, so this ADDS to core's `Module#include` instead of redeclaring it — a plain
  # redeclaration is a `DuplicatedMethodDefinitionError` that aborts the whole run.
  #
  # Sibling to `steep_ar_runtime` / `steep_controller_runtime` / `steep_actionview_runtime`,
  # which model a FRAMEWORK's runtime. This one models the language's, which is why it is
  # CORE rather than an extension: `include` is plain Ruby, so the litmus in
  # docs/engineering/keep-core-framework-agnostic.md ("would this make sense for a gem
  # that doesn't exist?") answers yes. `ActiveSupport::Concern` needs nothing of its own —
  # a Concern's `included` is a method its includers call the same way, and so is a
  # hand-rolled one.
  class RubyRuntimeGenerator
    # NOT dot-prefixed: these are `.rb` SOURCE files, and `**` skips hidden directories
    # — same reason as the AR-runtime sidecar.
    SIDECAR_DIR = "sig/generated/steep_ruby_runtime"

    # One emitted file: `filename` within the sidecar dir, `source` its contents.
    FileEntry = Struct.new(:filename, :source, keyword_init: true)

    MODULE_PSEUDO_CODE = <<~RUBY
      # frozen_string_literal: true
      #
      # GENERATED by RbsInfer::Project::RubyRuntimeGenerator.
      # Regenerated on every run; do not edit.

      class Module
        # What `include M` runs — `rb_mod_include` in MRI's eval.c, written in C, so no
        # source says it.
        #
        # `| ...` (rbs_infer#200) makes this ADD to core's `Module#include` rather than
        # redeclare it, which RBS rejects as a duplicate.
        # @rbs_infer |...
        def include(*modules)
          raise ArgumentError, "wrong number of arguments (given 0, expected 1+)" if modules.empty?

          # `while (argc--)`: backwards, which is why `include A, B` leaves A closest in
          # the ancestors. `send` because `rb_funcall` dispatches by name ignoring
          # visibility, and both of these are private on Module.
          modules.reverse_each do |mod|
            mod.send(:append_features, self)
            mod.send(:included, self)
          end

          self
        end

        # @rbs_infer |...
        def prepend(*modules)
          raise ArgumentError, "wrong number of arguments (given 0, expected 1+)" if modules.empty?

          modules.reverse_each do |mod|
            mod.send(:prepend_features, self)
            mod.send(:prepended, self)
          end

          self
        end

        # What `private_constant :X` runs — `rb_mod_private_constant` in MRI's
        # variable.c, written in C: it marks each named constant private, raising
        # `NameError` for one not defined, and answers the module. Marking is C no
        # Ruby spells, and it runs no method, so no hook of the project's either.
        # @rbs_infer |...
        def private_constant(*names)
          self
        end

        private

        # What `include` delegates the actual work to — `rb_mod_append_features` in eval.c:
        #
        #   if (!CLASS_OR_MODULE_P(include)) Check_Type(include, T_CLASS);
        #   rb_include_module(include, module);
        #   return module;
        #
        # The splice itself is `rb_include_module`, and no Ruby spells it — so the body says
        # the two things it CAN say: the type check, and that the answer is the module. A
        # module that overrides this (`ActiveSupport::Concern` does) now has a `super` to
        # resolve against. The check is a test of the object's type tag, which dispatches
        # nothing (`__rbs_infer__check_type`).
        # @rbs_infer |...
        def append_features(mod)
          __rbs_infer__check_type(mod)
          mod.send(:__rbs_infer__include_module, self)
          self
        end

        def __rbs_infer__include_module(mod)
        end

        # @rbs_infer |...
        def prepend_features(mod)
          __rbs_infer__check_type(mod)
          mod.send(:__rbs_infer__include_module, self)
          self
        end

        # @rbs_infer |...
        def prepended(base)
        end

        # The notification, and on `Module` it does nothing at all: `rb_obj_dummy1`, one
        # argument, returns nil. A module that wants to know overrides it with
        # `def self.included(base)`, which shadows this and is PUBLIC in the process — which
        # is why `include` above has to reach this one with `send`.
        # @rbs_infer |...
        def included(base)
        end

        # What `extend` delegates the singleton splice to — `rb_mod_extend_object`
        # in eval.c:
        #
        #   rb_extend_object(obj, mod);   /* rb_include_module(rb_singleton_class(obj), mod) */
        #   return obj;
        #
        # Same shape as `append_features` and unstatable for the same reason — the
        # splice is C — so the body says the one thing it can: the answer is the
        # OBJECT, not the module. That asymmetry is the difference between the two,
        # and a module that overrides this now has a `super` to resolve against.
        # @rbs_infer |...
        def extend_object(obj)
          obj.singleton_class.include(self)
          obj
        end

        # The notification, and on `Module` it does nothing at all: `rb_obj_dummy1`,
        # one argument, returns nil — the same stub as `included`. A module that
        # wants to know overrides it with `def self.extended(base)`, which shadows
        # this and is PUBLIC in the process, which is why `extend` reaches this one
        # with `send`.
        # @rbs_infer |...
        def extended(base)
        end
      end
    RUBY

    # `extend` is `Kernel#extend` (measured: `Object.instance_method(:extend).owner`),
    # and it is written here on `Object` instead, deliberately. What reads this file
    # resolves a core reopening through the SUPERCLASS chain, and no module is on one
    # — `Kernel` included. `Object` is on both the class chain and the module chain,
    # so it is where `extend` is reachable by the ancestry that does the reading, and
    # `class Object` is the cheaper claim than teaching that chain about modules.
    OBJECT_PSEUDO_CODE = <<~RUBY
      # frozen_string_literal: true
      #
      # GENERATED by RbsInfer::Project::RubyRuntimeGenerator.
      # Regenerated on every run; do not edit.

      class Object
        # What `obj.extend M` runs — `rb_obj_extend` in MRI's object.c, written in C,
        # so no source says it:
        #
        #   rb_check_arity(argc, 1, UNLIMITED_ARGUMENTS);
        #   for (i = 0; i < argc; i++) Check_Type(argv[i], T_MODULE);
        #   while (argc--) {
        #       rb_funcall(argv[argc], id_extend_object, 1, obj);
        #       rb_funcall(argv[argc], id_extended, 1, obj);
        #   }
        #   return obj;
        #
        # `| ...` (rbs_infer#200) makes this ADD to the `extend` core declares rather
        # than replace it — the declaration it adds to is `Kernel`'s, reached from here
        # because `Object` includes `Kernel`.
        # @rbs_infer |...
        def extend(*modules)
          raise ArgumentError, "wrong number of arguments (given 0, expected 1+)" if modules.empty?

          # `for (i = 0; i < argc; i++) Check_Type(...)`: EVERY argument is checked
          # before ANY hook runs, which is where this parts company with `include` —
          # there the check lives inside `append_features`, so `include Foo, 1` can
          # already have notified `Foo`.
          modules.each { |mod| __rbs_infer__check_type(mod) }

          # `while (argc--)`: backwards, as in `include`. `send` because `rb_funcall`
          # dispatches by name ignoring visibility, and both of these are private on
          # Module.
          modules.reverse_each do |mod|
            mod.send(:extend_object, self)
            mod.send(:extended, self)
          end

          self
        end

        private

        # `Check_Type` and `CLASS_OR_MODULE_P`: a test of the object's type tag, which
        # raises `TypeError` and calls no method. Any test Ruby spells dispatches one, so
        # the body is empty, like `__rbs_infer__include_module`.
        def __rbs_infer__check_type(value)
        end
      end
    RUBY

    # What `Class.new(superclass) { … }` runs — `rb_class_initialize` in MRI's
    # object.c, written in C:
    #
    #   if (RCLASS_SUPER(klass) != 0 || klass == rb_cBasicObject) rb_raise(rb_eTypeError, "already initialized class");
    #   if (rb_check_arity(argc, 0, 1) == 0) super = rb_cObject;
    #   else { super = argv[0]; rb_check_inheritable(super); ... }
    #   RCLASS_SET_SUPER(klass, super);
    #   rb_make_metaclass(klass, RBASIC(super)->klass);
    #   rb_class_inherited(super, klass);   /* rb_funcall(super, idInherited, 1, klass) */
    #   rb_mod_initialize_exec(klass);      /* if (rb_block_given_p()) rb_mod_module_exec(1, &klass, klass) */
    #
    # `class Sub < Superclass` reaches the same `rb_class_inherited` from
    # `vm_declare_class`, but no method call spells that one, so the checker
    # runs the hook there itself (felixefelip/steep#683). `inherited` on `Class`
    # is `rb_obj_class_inherited`, which does nothing; written here, a project
    # hook's `super` has a body to reach. Core's signatures are accurate, so
    # the defs declare none.
    CLASS_PSEUDO_CODE = <<~RUBY
      # frozen_string_literal: true
      #
      # GENERATED by RbsInfer::Project::RubyRuntimeGenerator.
      # Regenerated on every run; do not edit.

      class Class
        # What `Class.new(superclass) { … }` runs — `rb_class_initialize` in MRI's
        # object.c, written in C, so no source says it. `rb_funcall` is `send`, and
        # the block is run by `class_exec`, handed the class.
        # @rbs_infer no-signature
        def initialize(superclass = Object, &block)
          raise TypeError, "superclass must be an instance of Class (given an instance of \#{superclass.class})" unless superclass.is_a?(Class)
          raise TypeError, "can't make subclass of singleton class" if superclass.singleton_class?
          raise TypeError, "can't make subclass of Class" if superclass.equal?(Class)

          superclass.send(:inherited, self)
          class_exec(self, &block) if block
        end

        private

        # The notification, and on `Class` it does nothing at all:
        # `rb_obj_class_inherited`, one argument, returns nil.
        # @rbs_infer no-signature
        def inherited(subclass)
        end
      end
    RUBY

    # What `mutex.synchronize { … }` runs — `rb_mutex_synchronize_m` in MRI's
    # thread_sync.c, written in C:
    #
    #   if (!rb_block_given_p()) rb_raise(rb_eThreadError, "must be called with a block");
    #   return rb_mutex_synchronize(self, rb_yield, Qundef);
    #
    #   /* rb_mutex_synchronize */
    #   rb_mutex_lock(mutex);
    #   return rb_ensure(func, arg, rb_mutex_unlock, mutex);
    #
    # Core RBS says neither whether the block runs nor how often; the body says it
    # runs once, and that is what lets a store a block makes be followed past the
    # call (`@write_lock.synchronize { super }`, felixefelip/steep#370). Core's
    # signature is accurate, so the def declares none.
    THREAD_MUTEX_PSEUDO_CODE = <<~RUBY
      # frozen_string_literal: true
      #
      # GENERATED by RbsInfer::Project::RubyRuntimeGenerator.
      # Regenerated on every run; do not edit.

      class Thread::Mutex
        # What `synchronize` runs — `rb_mutex_synchronize_m` in MRI's thread_sync.c,
        # written in C, so no source says it. `rb_ensure` is `begin … ensure`.
        # @rbs_infer no-signature
        def synchronize
          raise ThreadError, "must be called with a block" unless block_given?

          lock
          begin
            yield
          ensure
            unlock
          end
        end
      end
    RUBY

    # What `ary.sum` runs — `rb_ary_sum` in MRI's array.c, written in C:
    #
    #   v = (rb_check_arity(argc, 0, 1) ? argv[0] : LONG2FIX(0));
    #   block_given = rb_block_given_p();
    #   ...
    #   for (; i < RARRAY_LEN(ary); i++) {
    #       e = RARRAY_AREF(ary, i);
    #       if (block_given)
    #           e = rb_yield(e);
    #       v = rb_funcall(v, idPLUS, 1, e);
    #   }
    #   return v;
    #
    # The paths before that loop add Integers, Rationals and Floats without
    # calling `+` (exactly, and Kahan-Babuska for Floats), and answer what `+`
    # would. Core declares the block and the return `untyped`, since a
    # signature cannot say "what `init + yield` is"; the body says it for each
    # call (felixefelip/rbs_infer#535). Core's signature stays, so the def
    # declares none.
    ARRAY_PSEUDO_CODE = <<~RUBY
      # frozen_string_literal: true
      #
      # GENERATED by RbsInfer::Project::RubyRuntimeGenerator.
      # Regenerated on every run; do not edit.

      class Array
        # What `sum` runs — `rb_ary_sum` in MRI's array.c, written in C, so no
        # source says it. `rb_funcall(v, idPLUS, 1, e)` is `value + element`.
        # @rbs_infer no-signature
        def sum(init = 0)
          value = init
          index = 0
          while index < length
            element = self[index]
            element = yield(element) if block_given?
            value += element
            index += 1
          end
          value
        end
      end
    RUBY

    # What `Hash.new` and `hash.default(key)` run — hash.rb and hash.c, in C:
    #
    #   def initialize(ifnone = (ifnone_unset = true), capacity: 0, &block)
    #     Primitive.rb_hash_init(capacity, ifnone_unset, ifnone, block)
    #   end
    #
    #   /* rb_hash_init */
    #   if (!NIL_P(block)) {
    #       if (ifnone_unset != Qtrue) rb_check_arity(1, 0, 0);
    #       else SET_PROC_DEFAULT(hash, block);
    #   }
    #   else RHASH_SET_IFNONE(hash, ifnone_unset == Qtrue ? Qnil : ifnone);
    #
    #   /* rb_hash_default */
    #   rb_check_arity(argc, 0, 1);
    #   ifnone = RHASH_IFNONE(hash);
    #   if (FL_TEST(hash, RHASH_PROC_DEFAULT)) {
    #       if (argc == 0) return Qnil;
    #       return call_default_proc(ifnone, hash, argv[0]);
    #   }
    #   return ifnone;
    #
    # `RHASH_IFNONE` holds the block or the value, told apart by a flag; written
    # as two ivars. A read of a key the table does not hold answers what
    # `default(key)` does (`rb_hash_default_value`), which is how the checker
    # reaches the block a `Hash.new { … }` kept (felixefelip/rbs_infer#623).
    # `Hash#[]` itself is not written: the checker follows what a hash holds,
    # and a body of the project's for it would turn that off. Core's
    # signatures are accurate, so the defs declare none.
    HASH_PSEUDO_CODE = <<~RUBY
      # frozen_string_literal: true
      #
      # GENERATED by RbsInfer::Project::RubyRuntimeGenerator.
      # Regenerated on every run; do not edit.

      class Hash
        # What `Hash.new` runs — `rb_hash_init` in MRI's hash.c, written in C.
        # @rbs_infer no-signature
        def initialize(ifnone = (ifnone_unset = true), capacity: 0, &block)
          if block
            raise ArgumentError, "wrong number of arguments (given 1, expected 0)" unless ifnone_unset

            @__rbs_infer__default_proc = block
          else
            @__rbs_infer__ifnone = ifnone_unset ? nil : ifnone
          end
        end

        # What `hash.default(key)` answers — `rb_hash_default` in MRI's hash.c.
        # `call_default_proc` calls the block with the hash and the key.
        # @rbs_infer no-signature
        def default(key = (key_unset = true))
          default_proc = @__rbs_infer__default_proc
          if default_proc
            return nil if key_unset

            return default_proc.call(self, key)
          end

          @__rbs_infer__ifnone
        end
      end
    RUBY

    # What `Thread.current`, `Thread#[]` and `Thread#[]=` run — thread.c, in C:
    #
    #   /* rb_thread_s_current */ return GET_THREAD()->self;
    #
    #   /* threadptr_local_aref */
    #   if (local_storage != NULL && rb_id_table_lookup(local_storage, id, &val)) return val;
    #   return Qnil;
    #
    #   /* threadptr_local_aset */
    #   if (NIL_P(val)) { if (!local_storage) return Qnil; rb_id_table_delete(local_storage, id); return Qnil; }
    #   if (local_storage == NULL) th->ec->local_storage = local_storage = rb_id_table_create(0);
    #   rb_id_table_insert(local_storage, id, val);
    #   return val;
    #
    # The main thread is allocated by `Init_Thread`, not built by `new` (which
    # raises without a block), and its fiber-local storage starts NULL.
    # `rb_check_id` takes a Symbol as it is and a String, or what converts
    # with `to_str`, as the Symbol it names. Core
    # declares `[]` as `-> untyped`, which stops a call site's value from
    # reaching the body, so `[]` and `[]=` add the signatures their call sites
    # infer ahead of core's; `current` keeps core's, which is accurate.
    THREAD_PSEUDO_CODE = <<~RUBY
      # frozen_string_literal: true
      #
      # GENERATED by RbsInfer::Project::RubyRuntimeGenerator.
      # Regenerated on every run; do not edit.

      class Thread
        # What `Thread.current` answers — `rb_thread_s_current` in MRI's thread.c.
        # @rbs_infer no-signature
        def self.current
          @__rbs_infer__main ||= allocate
        end

        # What `thread[key]` reads — `threadptr_local_aref` in MRI's thread.c.
        # @rbs_infer |...
        def [](key)
          locals = @__rbs_infer__locals
          return nil unless locals

          case key
          when Symbol then locals[key]
          else locals[key.to_str.to_sym]
          end
        end

        # What `thread[key] = value` writes — `threadptr_local_aset` in MRI's thread.c.
        # @rbs_infer |...
        def []=(key, value)
          id = case key
               when Symbol then key
               else key.to_str.to_sym
               end
          if value.nil?
            @__rbs_infer__locals&.delete(id)
            return nil
          end

          (@__rbs_infer__locals ||= Hash.new)[id] = value
        end
      end
    RUBY

    def initialize(app_dir:)
      @app_dir = app_dir
    end

    # Returns [FileEntry]. Public so specs can read the pseudo-code without touching disk.
    # The one constant the interpreter defines that code branches on to pick an
    # implementation (`RUBY_ENGINE == "jruby"`). Core RBS declares it `String`;
    # the value is the interpreter's, so it is written as the one running this,
    # and frozen so that no mention can change it (felixefelip/rbs_infer#506).
    def ruby_engine_pseudo_code
      <<~RUBY
        # frozen_string_literal: true
        #
        # GENERATED by RbsInfer::Project::RubyRuntimeGenerator.
        # Regenerated on every run; do not edit.

        RUBY_ENGINE = #{RUBY_ENGINE.inspect}
      RUBY
    end

    def build
      [FileEntry.new(filename: "module.rb", source: MODULE_PSEUDO_CODE),
       FileEntry.new(filename: "object.rb", source: OBJECT_PSEUDO_CODE),
       FileEntry.new(filename: "class.rb", source: CLASS_PSEUDO_CODE),
       FileEntry.new(filename: "ruby_engine.rb", source: ruby_engine_pseudo_code),
       FileEntry.new(filename: "thread_mutex.rb", source: THREAD_MUTEX_PSEUDO_CODE),
       FileEntry.new(filename: "thread.rb", source: THREAD_PSEUDO_CODE),
       FileEntry.new(filename: "array.rb", source: ARRAY_PSEUDO_CODE),
       FileEntry.new(filename: "hash.rb", source: HASH_PSEUDO_CODE)]
    end

    # (Re)writes the sidecar directory.
    def generate
      dir = File.join(@app_dir, SIDECAR_DIR)

      FileUtils.rm_rf(dir)
      FileUtils.mkdir_p(dir)
      build.each { |file| File.write(File.join(dir, file.filename), file.source) }

      dir
    end
  end
